import { z } from "zod";

// Rules for creating a product
export const createProductSchema = z.object({
  name: z.string().trim().min(2).max(100),

  description: z.string().trim().max(1000).optional(),

  // Product price must be a number greater than zero
  price: z.coerce.number().positive(),

  // Stock can be zero, but it cannot be negative
  stock: z.coerce.number().int().min(0),

  category: z.string().trim().min(2).max(50),
});

// Updating a product uses the same fields,
// but every field becomes optional.
export const updateProductSchema = createProductSchema
  .partial()
  .refine(
    (data) => Object.keys(data).length > 0,
    "Provide at least one field to update",
  );

// Rules for pagination query parameters
export const listProductsSchema = z.object({
  page: z.coerce.number().int().positive().default(1),

  // Prevent someone from requesting an extremely large page
  limit: z.coerce.number().int().positive().max(100).default(10),
});

// Product IDs are UUIDs generated by the application
export const productIdSchema = z.object({
  id: z.string().uuid(),
});

// Validate cursor pagination query parameters.
export const cursorPaginationSchema = z.object({
  // Return 20 products unless the client requests another amount.
  limit: z.coerce.number().int().min(1).max(100).default(20),

  // The first request doesn't have a cursor.
  // Later requests use the cursor returned by the API.
  cursor: z.string().min(1).max(1024).optional(),
});
