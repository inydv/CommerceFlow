import { performance } from "node:perf_hooks";

import { env } from "../../src/config/env.js";
import { pool } from "../../src/config/database.js";
import { logger } from "../../src/common/logger/logger.js";

// Explicit profiles accidental huge data generation prevent karte hain.
const profiles = {
  small: 1_000,
  medium: 10_000,
  large: 100_000,
};

const profile = process.argv[2] ?? "small";
const target = profiles[profile];

// Only development environment may run synthetic seeding.
// WHY: Production customers' data ko seed script accidentally
// modify nahi karni chahiye.
if (env.NODE_ENV !== "development") {
  throw new Error("Catalog seeding allowed only in development");
}

if (!target) {
  throw new Error("Use profile: small, medium or large");
}

const BATCH_SIZE = 500;
const CATEGORY_COUNT = 100;

// Fixed, reproducible slug.
// Same index always maps to same category.
function categorySlug(i) {
  return `seed-category-${String(i).padStart(3, "0")}`;
}

async function seedCategories() {
  const values = [];
  const rows = [];

  for (let i = 1; i <= CATEGORY_COUNT; i++) {
    values.push(`Demo Category ${i}`, categorySlug(i));

    const position = values.length;
    rows.push(`($${position - 1}, $${position})`);
  }

  // Idempotent insert.
  // Existing category slugs stay unchanged on reruns.
  await pool.query(
    `INSERT INTO categories (name, slug)
     VALUES ${rows.join(", ")}
     ON CONFLICT (slug) DO NOTHING`,
    values,
  );

  const result = await pool.query(
    `SELECT id, slug
     FROM categories
     WHERE slug LIKE 'seed-category-%'`,
  );

  const bySlug = new Map(result.rows.map((row) => [row.slug, row.id]));

  // Do not seed products if any expected category is missing.
  for (let i = 1; i <= CATEGORY_COUNT; i++) {
    if (!bySlug.has(categorySlug(i))) {
      throw new Error(`Missing seed category ${i}`);
    }
  }

  return bySlug;
}

function makeProduct(i, categories) {
  const categoryNumber = ((i - 1) % CATEGORY_COUNT) + 1;

  return {
    sku: `SEED-P${String(i).padStart(6, "0")}`,
    name: `CommerceFlow Demo Product ${i}`,
    description: `Synthetic learning product ${i}`,

    categoryId: categories.get(categorySlug(categoryNumber)),

    // Deterministic integer prices in paise.
    priceMinor: 10000 + ((i * 7919) % 9_000_000),

    // Mixed product states for meaningful SQL filters.
    status: i % 20 === 0 ? "archived" : i % 10 === 0 ? "draft" : "active",
  };
}

async function insertBatch(start, end, categories) {
  const values = [];
  const rows = [];

  // Only current 500 product values remain in this batch.
  // WHY: 100,000 product objects memory mein hold nahi karne.
  for (let i = start; i <= end; i++) {
    const product = makeProduct(i, categories);

    values.push(
      product.sku,
      product.name,
      product.description,
      product.categoryId,
      product.priceMinor,
      product.status,
    );

    const first = values.length - 5;

    // Placeholders generated by code, never from user SQL.
    rows.push(
      `(${Array.from({ length: 6 }, (_, j) => `$${first + j}`).join(", ")})`,
    );
  }

  // One query inserts up to 500 records.
  // WITHOUT BATCHING: 100k separate DB round trips
  // may significantly increase seeding duration.
  //
  // Same SKU on rerun -> skip rather than overwrite.
  const result = await pool.query(
    `INSERT INTO products (
       sku, name, description,
       category_id, price_minor, status
     )
     VALUES ${rows.join(", ")}
     ON CONFLICT (sku) DO NOTHING`,
    values,
  );

  return result.rowCount;
}

async function main() {
  const started = performance.now();
  const categories = await seedCategories();

  let inserted = 0;

  for (let start = 1; start <= target; start += BATCH_SIZE) {
    const end = Math.min(start + BATCH_SIZE - 1, target);

    inserted += await insertBatch(start, end, categories);

    // Log every 10 batches instead of flooding stdout.
    if (end % 5000 === 0 || end === target) {
      logger.info({ processed: end, target }, "Catalog seed progress");
    }
  }

  // Refresh planner stats after large inserts.
  // WHY: PostgreSQL can choose better query plans
  // when table statistics reflect actual data.
  await pool.query("ANALYZE categories");
  await pool.query("ANALYZE products");

  logger.info(
    {
      profile,
      target,
      newlyInserted: inserted,
      durationMs: Math.round(performance.now() - started),
    },
    "Catalog seeding completed",
  );
}

try {
  await main();
} catch (error) {
  logger.error({ err: error }, "Catalog seeding failed");
  process.exitCode = 1;
} finally {
  // This is a one-off CLI script: drain pool before exit.
  await pool.end();
}
